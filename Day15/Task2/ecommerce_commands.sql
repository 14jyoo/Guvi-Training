DESCRIBE TABLE ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE;

SELECT
    INVOICE_NO,
    COUNT(*) AS RECORD_COUNT
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE
GROUP BY INVOICE_NO
HAVING COUNT(*) > 1
ORDER BY RECORD_COUNT DESC;

SELECT *
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE
WHERE QUANTITY <= 0
ORDER BY QUANTITY;

SELECT COUNT(*) AS TOTAL_RECORDS
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE;

SELECT
    MIN(QUANTITY) AS MIN_QUANTITY,
    MAX(QUANTITY) AS MAX_QUANTITY,
    COUNT(*) AS TOTAL_RECORDS,
    SUM(CASE WHEN QUANTITY <= 0 THEN 1 ELSE 0 END)
        AS NON_POSITIVE_QUANTITY_ROWS
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE;

SELECT
    MIN(QUANTITY) AS MIN_QUANTITY,
    MAX(QUANTITY) AS MAX_QUANTITY,
    ROUND(AVG(QUANTITY), 2) AS AVG_QUANTITY,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    MEDIAN(QUANTITY) AS MEDIAN_QUANTITY
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE; 

SELECT
    ROUND(SUM(REVENUE), 2) AS TOTAL_REVENUE
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE;

SELECT
    COUNTRY,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    ROUND(SUM(REVENUE), 2) AS TOTAL_REVENUE
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE
GROUP BY COUNTRY
ORDER BY TOTAL_REVENUE DESC;

SELECT
    STOCK_CODE,
    DESCRIPTION,
    SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD,
    ROUND(SUM(REVENUE), 2) AS TOTAL_REVENUE
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE
GROUP BY STOCK_CODE, DESCRIPTION
ORDER BY TOTAL_REVENUE DESC;

SELECT
    TO_DATE(INVOICE_DATE) AS SALES_DATE,
    COUNT(DISTINCT INVOICE_NO) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    ROUND(SUM(REVENUE), 2) AS DAILY_REVENUE
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE
GROUP BY TO_DATE(INVOICE_DATE)
ORDER BY SALES_DATE;

WITH QUARTILES AS (
    SELECT
        PERCENTILE_CONT(0.25)
            WITHIN GROUP (ORDER BY QUANTITY) AS Q1,
        PERCENTILE_CONT(0.75)
            WITHIN GROUP (ORDER BY QUANTITY) AS Q3
    FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE
    WHERE QUANTITY IS NOT NULL
),
BOUNDS AS (
    SELECT
        Q1,
        Q3,
        Q3 - Q1 AS IQR,
        Q1 - 1.5 * (Q3 - Q1) AS LOWER_BOUND,
        Q3 + 1.5 * (Q3 - Q1) AS UPPER_BOUND
    FROM QUARTILES
)
SELECT
    E.*,
    B.LOWER_BOUND,
    B.UPPER_BOUND
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE E
CROSS JOIN BOUNDS B
WHERE E.QUANTITY < B.LOWER_BOUND
   OR E.QUANTITY > B.UPPER_BOUND
ORDER BY E.QUANTITY;

SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT INVOICE_NO) AS UNIQUE_INVOICES,
    COUNT(DISTINCT STOCK_CODE) AS UNIQUE_PRODUCTS,
    COUNT(DISTINCT COUNTRY) AS UNIQUE_COUNTRIES,
    SUM(QUANTITY) AS TOTAL_QUANTITY,
    ROUND(SUM(REVENUE), 2) AS TOTAL_REVENUE,
    SUM(CASE WHEN QUANTITY <= 0 THEN 1 ELSE 0 END)
        AS NON_POSITIVE_QUANTITY_ROWS,
    SUM(CASE WHEN UNIT_PRICE <= 0 THEN 1 ELSE 0 END)
        AS NON_POSITIVE_PRICE_ROWS
FROM ECOMMERCE_DB.RAW.CLEANED_ECOMMERCE;
