CREATE DATABASE IF NOT EXISTS AMAZON_ANALYTICS_DB;

CREATE WAREHOUSE IF NOT EXISTS AMAZON_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE SCHEMA IF NOT EXISTS
AMAZON_ANALYTICS_DB.PUBLIC;


USE ROLE SYSADMIN;

USE WAREHOUSE AMAZON_WH;

USE DATABASE AMAZON_ANALYTICS_DB;

USE SCHEMA PUBLIC;

CREATE OR REPLACE TABLE AMAZON_PRODUCTS_RAW
(
    PRODUCT_ID VARCHAR,
    PRODUCT_NAME VARCHAR,
    CATEGORY VARCHAR,
    DISCOUNTED_PRICE VARCHAR,
    ACTUAL_PRICE VARCHAR,
    DISCOUNT_PERCENTAGE VARCHAR,
    RATING VARCHAR,
    RATING_COUNT VARCHAR,
    ABOUT_PRODUCT VARCHAR,
    USER_ID VARCHAR,
    USER_NAME VARCHAR,
    REVIEW_ID VARCHAR,
    REVIEW_TITLE VARCHAR,
    REVIEW_CONTENT VARCHAR,
    IMG_LINK VARCHAR,
    PRODUCT_LINK VARCHAR
);


CREATE OR REPLACE FILE FORMAT AMAZON_CSV_FORMAT
TYPE = CSV
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
SKIP_HEADER = 1
TRIM_SPACE = TRUE
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('NULL', 'null')
MULTI_LINE = TRUE;


CREATE OR REPLACE STAGE AMAZON_STAGE
FILE_FORMAT = AMAZON_CSV_FORMAT;

LIST @AMAZON_STAGE;

COPY INTO AMAZON_PRODUCTS_RAW
FROM @AMAZON_STAGE
FILE_FORMAT = (
    FORMAT_NAME = AMAZON_CSV_FORMAT
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT *
FROM AMAZON_PRODUCTS_RAW
LIMIT 10;

SELECT COUNT(*) AS TOTAL_RECORDS
FROM AMAZON_PRODUCTS_RAW;

SELECT
    PRODUCT_ID,
    COUNT(*) AS RECORD_COUNT
FROM AMAZON_PRODUCTS_RAW
GROUP BY PRODUCT_ID
HAVING COUNT(*) > 1
ORDER BY RECORD_COUNT DESC;


CREATE OR REPLACE TABLE AMAZON_PRODUCTS AS

SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,

    TRY_TO_DECIMAL(
        REGEXP_REPLACE(
            DISCOUNTED_PRICE,
            '[^0-9.]',
            ''
        ),
        12,2
    ) AS DISCOUNTED_PRICE,

    TRY_TO_DECIMAL(
        REGEXP_REPLACE(
            ACTUAL_PRICE,
            '[^0-9.]',
            ''
        ),
        12,2
    ) AS ACTUAL_PRICE,

    TRY_TO_DECIMAL(
        REPLACE(DISCOUNT_PERCENTAGE, '%', ''),
        5,2
    ) AS DISCOUNT_PERCENTAGE,

    TRY_TO_DOUBLE(
        NULLIF(RATING, '|')
    ) AS RATING,

    TRY_TO_NUMBER(
        REPLACE(RATING_COUNT, ',', '')
    ) AS RATING_COUNT,

    ABOUT_PRODUCT,
    USER_ID,
    USER_NAME,
    REVIEW_ID,
    REVIEW_TITLE,
    REVIEW_CONTENT,
    IMG_LINK,
    PRODUCT_LINK,

    SPLIT_PART(CATEGORY, '|', 1)
        AS MAIN_CATEGORY,

    SPLIT_PART(CATEGORY, '|', 2)
        AS SUB_CATEGORY,

    SPLIT_PART(CATEGORY, '|', 3)
        AS SUB_CATEGORY_LEVEL_2,

    (
        TRY_TO_DECIMAL(
            REGEXP_REPLACE(ACTUAL_PRICE, '[^0-9.]', ''),
            12,2
        )
        -
        TRY_TO_DECIMAL(
            REGEXP_REPLACE(DISCOUNTED_PRICE, '[^0-9.]', ''),
            12,2
        )
    ) AS PRICE_SAVINGS

FROM AMAZON_PRODUCTS_RAW;

SELECT COUNT(*)
FROM AMAZON_PRODUCTS;

SELECT
    PRODUCT_ID,
    DISCOUNTED_PRICE,
    ACTUAL_PRICE,
    DISCOUNT_PERCENTAGE,
    RATING,
    RATING_COUNT,
    MAIN_CATEGORY,
    SUB_CATEGORY,
    PRICE_SAVINGS
FROM AMAZON_PRODUCTS
LIMIT 10;

SELECT
    COUNT_IF(DISCOUNTED_PRICE IS NULL)
        AS MISSING_DISCOUNTED_PRICE,

    COUNT_IF(ACTUAL_PRICE IS NULL)
        AS MISSING_ACTUAL_PRICE,

    COUNT_IF(RATING IS NULL)
        AS MISSING_RATING,

    COUNT_IF(RATING_COUNT IS NULL)
        AS MISSING_RATING_COUNT

FROM AMAZON_PRODUCTS;


SELECT
    MAIN_CATEGORY,
    COUNT(*) AS PRODUCT_RECORDS,
    ROUND(AVG(RATING), 2) AS AVERAGE_RATING,
    ROUND(AVG(DISCOUNT_PERCENTAGE), 2)
        AS AVERAGE_DISCOUNT

FROM AMAZON_PRODUCTS

GROUP BY MAIN_CATEGORY

ORDER BY PRODUCT_RECORDS DESC;


SELECT
    RATING,
    COUNT(*) AS PRODUCT_COUNT

FROM AMAZON_PRODUCTS

GROUP BY RATING

ORDER BY RATING DESC;



