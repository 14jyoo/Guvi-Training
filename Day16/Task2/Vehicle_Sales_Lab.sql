CREATE OR REPLACE TABLE CUSTOMERS AS
SELECT
    UPPER(TRIM(CUSTOMER_ID)) AS CUSTOMER_ID,

    COALESCE(
        NULLIF(TRIM(CUSTOMER_NAME), ''),
        'Unknown'
    ) AS CUSTOMER_NAME,

    COALESCE(
        UPPER(NULLIF(TRIM(CUSTOMER_TYPE), '')),
        'UNKNOWN'
    ) AS CUSTOMER_TYPE,

    UPPER(NULLIF(TRIM(CITY), '')) AS CITY,

    UPPER(NULLIF(TRIM(STATE), '')) AS STATE,

    NULLIF(TRIM(EMAIL), '') AS EMAIL,

    TRY_TO_DATE(
        NULLIF(TRIM(SIGNUP_DATE), ''),
        'YYYY-MM-DD'
    ) AS SIGNUP_DATE

FROM VEHICLE_SALES_RAW

WHERE NULLIF(TRIM(CUSTOMER_ID), '') IS NOT NULL

AND (
    NULLIF(TRIM(CUSTOMER_NAME), '') IS NOT NULL
    OR NULLIF(TRIM(CITY), '') IS NOT NULL
    OR NULLIF(TRIM(EMAIL), '') IS NOT NULL
)

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY UPPER(TRIM(CUSTOMER_ID))
    ORDER BY SIGNUP_DATE DESC
) = 1;

CREATE OR REPLACE TABLE VEHICLE_ORDERS AS
SELECT
    TRIM(ORDER_ID) AS ORDER_ID,

    NULLIF(TRIM(ORDER_DATE), '') AS ORDER_DATE,

    NULLIF(UPPER(TRIM(CUSTOMER_ID)), '') AS CUSTOMER_ID,

    NULLIF(TRIM(VEHICLE_ID), '') AS VEHICLE_ID,

    NULLIF(TRIM(BRAND), '') AS BRAND,

    NULLIF(TRIM(MODEL), '') AS MODEL,

    NULLIF(TRIM(VEHICLE_TYPE), '') AS VEHICLE_TYPE,

    NULLIF(TRIM(QUANTITY), '') AS QUANTITY,

    NULLIF(TRIM(UNIT_PRICE), '') AS UNIT_PRICE,

    NULLIF(TRIM(DISCOUNT), '') AS DISCOUNT,

    UPPER(NULLIF(TRIM(PAYMENT_STATUS), '')) AS PAYMENT_STATUS,

    NULLIF(TRIM(DEALERSHIP_LOCATION), '') AS DEALERSHIP_LOCATION

FROM VEHICLE_SALES_RAW;

