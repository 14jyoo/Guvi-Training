WITH VALID_SALES AS (
    SELECT
        ORDER_ID,
        TRY_TO_DECIMAL(QUANTITY, 12, 2) AS QTY,
        TRY_TO_DECIMAL(UNIT_PRICE, 14, 2) AS PRICE,

        COALESCE(
            TRY_TO_DECIMAL(
                NULLIF(TRIM(DISCOUNT), ''),
                14, 2
            ), 0
        ) AS DISC

    FROM VEHICLE_ORDERS

    WHERE PAYMENT_STATUS IN ('PAID', 'FINANCED')
)

SELECT
    COUNT(DISTINCT ORDER_ID) AS TOTAL_SALES,

    ROUND(
        SUM(QTY * (PRICE - DISC)), 2
    ) AS TOTAL_REVENUE

FROM VALID_SALES

WHERE QTY > 0
AND PRICE > 0;


SELECT
    BRAND,
    MODEL,

    SUM(
        TRY_TO_DECIMAL(QUANTITY, 12, 2)
    ) AS VEHICLES_SOLD,

    ROUND(
        SUM(
            TRY_TO_DECIMAL(QUANTITY, 12, 2)
            *
            (
                TRY_TO_DECIMAL(UNIT_PRICE, 14, 2)
                -
                COALESCE(
                    TRY_TO_DECIMAL(
                        NULLIF(TRIM(DISCOUNT), ''),
                        14, 2
                    ), 0
                )
            )
        ), 2
    ) AS PRODUCT_REVENUE

FROM VEHICLE_ORDERS

WHERE PAYMENT_STATUS IN ('PAID', 'FINANCED')
AND TRY_TO_DECIMAL(QUANTITY, 12, 2) > 0
AND TRY_TO_DECIMAL(UNIT_PRICE, 14, 2) > 0
AND BRAND IS NOT NULL
AND MODEL IS NOT NULL

GROUP BY BRAND, MODEL

ORDER BY PRODUCT_REVENUE DESC;



SELECT
    O.ORDER_ID,
    O.ORDER_DATE,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CUSTOMER_TYPE,
