INNER JOIN CUSTOMERS C

ON UPPER(TRIM(O.CUSTOMER_ID)) = C.CUSTOMER_ID

ORDER BY O.ORDER_ID;



SELECT
    O.ORDER_ID,
    O.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.BRAND,
    O.MODEL

FROM VEHICLE_ORDERS O

LEFT JOIN CUSTOMERS C

ON UPPER(TRIM(O.CUSTOMER_ID)) = C.CUSTOMER_ID

WHERE C.CUSTOMER_ID IS NULL;



WITH SALES AS (
    SELECT
        C.CUSTOMER_TYPE,
        O.ORDER_ID,

        TRY_TO_DECIMAL(O.QUANTITY, 12, 2) AS QTY,

        TRY_TO_DECIMAL(O.UNIT_PRICE, 14, 2) AS PRICE,

        COALESCE(
            TRY_TO_DECIMAL(
                NULLIF(TRIM(O.DISCOUNT), ''),
                14, 2
            ), 0
        ) AS DISC

    FROM VEHICLE_ORDERS O

    INNER JOIN CUSTOMERS C
        ON UPPER(TRIM(O.CUSTOMER_ID)) = C.CUSTOMER_ID

    WHERE O.PAYMENT_STATUS IN ('PAID', 'FINANCED')
)

SELECT
    CUSTOMER_TYPE,

    COUNT(DISTINCT ORDER_ID) AS TOTAL_SALES,

    ROUND(
        SUM(QTY * (PRICE - DISC)), 2
    ) AS TOTAL_REVENUE

FROM SALES

WHERE QTY > 0
AND PRICE > 0

GROUP BY CUSTOMER_TYPE

ORDER BY TOTAL_REVENUE DESC;


